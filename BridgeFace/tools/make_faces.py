#!/usr/bin/env python3
"""Makes the two BridgeFace backgrounds and icons from their source photos.

The screen is 240x240 with four levels per channel, and the images are dithered
here because the build doesn't. The percent sign is drawn into the image because
the app's generated fonts have no such glyph, and tgfx, which makes them, isn't
available on a Mac. MainView right-aligns the battery number against it.

Usage: make_faces.py <folder with the photos> <Poppins-SemiBold.ttf> [preview.png]

Photos, from Wikimedia Commons, 960 pixel thumbnails:
  arches.jpg  File:Atlantic_Coast_Line_Railroad_Bridge.jpg, Eli Christman, CC BY 2.0
  sunset.jpg  File:Atlantic_coastline_trestle.jpg, Kwhopson, public domain
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFont

FACES = Path(__file__).resolve().parent.parent / "Faces"
SIZE = 240
LEVELS = [0, 85, 170, 255]

# (crop in the photo, y where darkening starts, y where it ends, how dark it ends)
PHOTOS = {
    "Arches": ("arches.jpg", (190, 0, 910, 720), 84, 132, 0.30),
    "Sunset": ("sunset.jpg", (230, 140, 730, 640), 110, 140, 0.55),
}

# Must match MainView.cpp.
PERCENT_X = 126
BATTERY_BASELINE = 197
CLOCK_BASELINE = 175


def palette():
    image = Image.new("P", (1, 1))
    colors = [c for r in LEVELS for g in LEVELS for b in LEVELS for c in (r, g, b)]
    image.putpalette(colors + [0, 0, 0] * (256 - 64))
    return image


def darken(image, start, end, floor):
    """Darkens from a row downward, so white type stays readable."""
    dark = ImageEnhance.Brightness(image).enhance(floor)
    ramp = Image.new("L", (SIZE, SIZE))
    for y in range(SIZE):
        share = min(max((y - start) / (end - start), 0), 1)
        ramp.paste(int(share * 255), (0, y, SIZE, y + 1))
    return Image.composite(dark, image, ramp)


def background(photos, name, font):
    file, crop, start, end, floor = PHOTOS[name]
    image = Image.open(photos / file).convert("RGB").crop(crop).resize((SIZE, SIZE), Image.LANCZOS)
    image = ImageEnhance.Contrast(ImageEnhance.Color(image).enhance(1.25)).enhance(1.1)
    image = darken(image, start, end, floor)
    draw = ImageDraw.Draw(image)
    draw.text((PERCENT_X, BATTERY_BASELINE), "%", font=font, fill=(255, 255, 255), anchor="ls")
    return image.quantize(palette=palette(), dither=Image.Dither.FLOYDSTEINBERG)


def write_source(indexed, path):
    # ABGR2222: the index is r*16 + g*4 + b, and the byte is AA BB GG RR.
    pixels = []
    for index in indexed.tobytes():
        assert index < 64
        r, g, b = index >> 4, (index >> 2) & 3, index & 3
        pixels.append(0xC0 | b << 4 | g << 2 | r)
    rows = [", ".join(f"0x{p:02x}" for p in pixels[i:i + 12]) for i in range(0, len(pixels), 12)]
    body = ",\n    ".join(rows)
    path.write_text(
        "// Generated by BridgeFace/tools/make_faces.py. Please, do not edit!\n\n"
        "#include <touchgfx/hal/Config.hpp>\n\n"
        'LOCATION_PRAGMA("IntFlashSection")\n'
        'KEEP extern const unsigned char image_background_240x240[] LOCATION_ATTRIBUTE("IntFlashSection") = '
        "{ // 240x240 ABGR2222 pixels.\n"
        f"    {body}\n}};\n"
    )


def icon(photos, name, size):
    file, crop, *_ = PHOTOS[name]
    image = Image.open(photos / file).convert("RGB").crop(crop).resize((size, size), Image.LANCZOS).convert("RGBA")
    mask = Image.new("L", (size * 4, size * 4))
    ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    image.putalpha(mask.resize((size, size), Image.LANCZOS))
    return image


def preview(faces, ttf, path):
    """How each face should look, with sample readings at their real positions."""
    clock = ImageFont.truetype(ttf, 60)
    small = ImageFont.truetype(ttf, 16)
    round_mask = Image.new("L", (SIZE, SIZE))
    ImageDraw.Draw(round_mask).ellipse((0, 0, SIZE - 1, SIZE - 1), fill=255)
    sheet = Image.new("RGB", (len(faces) * 500 + 20, 520), (40, 40, 40))
    for slot, indexed in enumerate(faces):
        face = indexed.convert("RGB")
        draw = ImageDraw.Draw(face)
        draw.text((28, CLOCK_BASELINE), "10", font=clock, fill="white", anchor="ls")
        draw.text((112, CLOCK_BASELINE), ":", font=clock, fill="white", anchor="ls")
        draw.text((132, CLOCK_BASELINE), "42", font=clock, fill="white", anchor="ls")
        draw.text((PERCENT_X, BATTERY_BASELINE), "85", font=small, fill="white", anchor="rs")
        black = Image.new("RGB", (SIZE, SIZE))
        black.paste(face, (0, 0), round_mask)
        sheet.paste(black.resize((480, 480), Image.NEAREST), (20 + slot * 500, 20))
    sheet.save(path)


def main():
    photos, ttf = Path(sys.argv[1]), sys.argv[2]
    font = ImageFont.truetype(ttf, 16)
    made = []
    for name in PHOTOS:
        folder = FACES / name
        indexed = background(photos, name, font)
        indexed.convert("RGB").save(folder / "Background_240x240.png")
        write_source(indexed, folder / "image_Background_240x240.cpp")
        icon(photos, name, 60).save(folder / "icon_60x60.png")
        icon(photos, name, 30).save(folder / "icon_30x30.png")
        made.append(indexed)
    if len(sys.argv) > 3:
        preview(made, ttf, sys.argv[3])


main()
